import java.util.*;

public class StringConcateDemo {
    public static void main(String[] args) {
        String firstName = "Shreyansh";
        String lastName = "Jharia";
        
        // Combining firstName, a space, and lastName
        String fullName = firstName + " " + lastName;
        
        // Appending additional text in the print statement
        System.out.println(fullName + " is this your code");
        
        // Output: Shradha Khapra is this
    }
}