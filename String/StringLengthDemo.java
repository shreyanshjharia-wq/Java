import java.util.*;
public class StringLengthDemo {
    public static void main(String[] args) {
        String fullName = "Tony Stark";
        
        // .length() counts letters, symbols, and spaces
        System.out.println(fullName.length()); 
        
        // Output: 10 (Tony = 4, Space = 1, Stark = 5)
    }
}